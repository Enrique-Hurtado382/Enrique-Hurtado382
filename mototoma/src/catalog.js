export function getEdit(id) {
  return EDITS.find((e) => e.id === id) || null;
}

export function getShot(edit, shotId) {
  return edit.tomas.find((t) => t.id === shotId) || null;
}

/** Duración total de cada toma dentro del edit final (puede aparecer varias veces). */
export function usoEnEdit(edit, shotId) {
  return edit.estructura
    .filter((s) => s.toma === shotId)
    .reduce((sum, s) => sum + (s.hasta - s.desde), 0);
}

/** Tiempos de los golpes de ritmo dentro de la duración del edit. */
export function golpes(edit) {
  const beat = 60 / edit.bpm;
  const out = [];
  for (let t = 0; t <= edit.duracion + 1e-6; t += beat) out.push(+t.toFixed(3));
  return out;
}

/** Nombre de archivo ordenado para el editor: MotoToma_<edit>_T03_<toma>_<fecha>. */
export function nombreArchivo(edit, shot, fecha = new Date(), ext = 'mp4') {
  const n = String(edit.tomas.indexOf(shot) + 1).padStart(2, '0');
  const pad = (v) => String(v).padStart(2, '0');
  const stamp = `${fecha.getFullYear()}${pad(fecha.getMonth() + 1)}${pad(fecha.getDate())}_${pad(fecha.getHours())}${pad(fecha.getMinutes())}${pad(fecha.getSeconds())}`;
  return `MotoToma_${edit.id}_T${n}_${shot.id}_${stamp}.${ext}`;
}
